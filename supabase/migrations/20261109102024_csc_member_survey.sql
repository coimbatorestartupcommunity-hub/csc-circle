-- Private, unlisted CSC Circle member-information survey.
-- This is intentionally separate from memberships, profiles and startup records.

create table public.csc_members (
  id uuid primary key default gen_random_uuid(),
  full_name text not null,
  contact_number text not null,
  email text not null,
  member_category text not null,
  business_or_idea_name text not null,
  description text not null,
  consent_at timestamptz not null default now(),
  submission_source text not null default 'member_onboarding_survey',
  submission_token uuid not null,
  created_at timestamptz not null default now(),

  constraint csc_members_full_name_valid check (
    full_name = btrim(full_name)
    and char_length(full_name) between 2 and 120
  ),
  constraint csc_members_contact_number_valid check (
    contact_number = btrim(contact_number)
    and char_length(contact_number) between 7 and 30
    and contact_number ~ '^[+0-9() .-]+$'
  ),
  constraint csc_members_email_valid check (
    email = lower(btrim(email))
    and char_length(email) between 3 and 254
    and email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'
  ),
  constraint csc_members_category_valid check (
    member_category in ('Established Business', 'Startup Founder', 'Idea Stage')
  ),
  constraint csc_members_business_name_valid check (
    business_or_idea_name = btrim(business_or_idea_name)
    and char_length(business_or_idea_name) between 2 and 160
  ),
  constraint csc_members_description_valid check (
    description = btrim(description)
    and char_length(description) between 10 and 3000
  ),
  constraint csc_members_submission_source_valid check (
    submission_source = 'member_onboarding_survey'
  ),
  constraint csc_members_submission_token_unique unique (submission_token)
);

create index csc_members_category_created_idx
  on public.csc_members (member_category, created_at desc);
create index csc_members_created_idx
  on public.csc_members (created_at desc);
create index csc_members_full_name_search_idx
  on public.csc_members (lower(full_name));
create index csc_members_email_search_idx
  on public.csc_members (lower(email));
create index csc_members_business_name_search_idx
  on public.csc_members (lower(business_or_idea_name));

alter table public.csc_members enable row level security;
alter table public.csc_members force row level security;

-- No anon/authenticated policy exists: browsers cannot read, update or delete
-- survey responses and cannot bypass the validated application submission path.
revoke all on table public.csc_members from public, anon, authenticated;
grant select, insert, update, delete on table public.csc_members to service_role;

comment on table public.csc_members is
  'Private CSC member-onboarding survey responses; not authenticated membership accounts.';
comment on column public.csc_members.submission_token is
  'Opaque idempotency token generated by the survey client; never used as the row identifier.';
comment on column public.csc_members.consent_at is
  'Time at which the required survey privacy notice was accepted.';

-- Parameterized, bounded search used only by the trusted server client. Keeping
-- the filter construction in SQL prevents PostgREST filter-grammar injection.
create or replace function public.csc_list_member_survey_responses(
  p_category text default null,
  p_search text default null,
  p_sort text default 'newest',
  p_offset integer default 0,
  p_limit integer default 25
)
returns table (
  id uuid,
  full_name text,
  contact_number text,
  email text,
  member_category text,
  business_or_idea_name text,
  description text,
  consent_at timestamptz,
  submission_source text,
  created_at timestamptz,
  total_count bigint
)
language sql
stable
security invoker
set search_path = ''
as $$
  select
    members.id,
    members.full_name,
    members.contact_number,
    members.email,
    members.member_category,
    members.business_or_idea_name,
    members.description,
    members.consent_at,
    members.submission_source,
    members.created_at,
    count(*) over () as total_count
  from public.csc_members as members
  where
    (p_category is null or members.member_category = p_category)
    and (
      nullif(btrim(p_search), '') is null
      or members.full_name ilike '%' || p_search || '%'
      or members.email ilike '%' || p_search || '%'
      or members.business_or_idea_name ilike '%' || p_search || '%'
      or members.contact_number ilike '%' || p_search || '%'
    )
  order by
    case when p_sort = 'newest' then members.created_at end desc,
    case when p_sort = 'oldest' then members.created_at end asc,
    case when p_sort = 'name_asc' then lower(members.full_name) end asc,
    case when p_sort = 'name_desc' then lower(members.full_name) end desc,
    members.id asc
  offset greatest(coalesce(p_offset, 0), 0)
  limit least(greatest(coalesce(p_limit, 25), 1), 500);
$$;

revoke all on function public.csc_list_member_survey_responses(text, text, text, integer, integer)
  from public, anon, authenticated;
grant execute on function public.csc_list_member_survey_responses(text, text, text, integer, integer)
  to service_role;
